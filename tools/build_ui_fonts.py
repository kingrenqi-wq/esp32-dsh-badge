#!/usr/bin/env python3
"""Reproducible 4bpp UI fonts. Inter (Latin) + Noto Sans SC (CJK), both SIL OFL 1.1.
Run with Pillow. 字体文件不进仓库，缺了就按下面命令下载：
    mkdir -p fonts
    curl -L -o fonts/Inter.ttf "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/Inter%5Bopsz,wght%5D.ttf"
    curl -L -o fonts/NotoSansSC.ttf "https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf"
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import sys
ROOT=Path(__file__).resolve().parents[1]
def find_font(name):
    for d in (ROOT/'fonts', Path('/tmp/fonts')):
        f=d/name
        if f.exists(): return f
    sys.exit(f'缺字体文件 {name}；见本文件顶部注释里的下载命令')
LATIN_FILE=find_font('Inter.ttf')
CJK_FILE=find_font('NotoSansSC.ttf')
ASCII=' 0123456789.:/-+%CPUDBKMGs¥°'
CJK='内存磁盘可用余额思考中已完成空闲出错未连接镜像键返回专会分注花话费轮长活动有包均按本算能还钱晴多云阴雾雨雪雷阵毛风周一二三四五六日月天气沙城最高低湿度速明后今预报出落温来小时近合计次调用元七级力'
SPECS=[('UI14',14,ASCII+CJK),('UI16',16,ASCII+CJK),('UI18',18,ASCII+CJK),
       ('NUM12',12,'0123456789.:/-'),('NUM20',20,'0123456789.:-'),('NUM24',24,'0123456789.:-'),
       ('NUM28',28,'0123456789.:-'),('CLOCK52',52,'0123456789:.-')]
lines=['// Generated by tools/build_ui_fonts.py; 4bpp, baseline-relative glyphs.',
       '#pragma once','#include <stdint.h>',
       'struct UiGlyph { uint32_t cp, offset; uint8_t w, h, advance; int8_t x, y; };',
       'struct UiFont { const UiGlyph *glyphs; const uint8_t *data; uint16_t count; };']
for name,size,chars in SPECS:
    chars=''.join(dict.fromkeys(chars))
    latin=ImageFont.truetype(str(LATIN_FILE),size*4)
    try: latin.set_variation_by_axes([14,500])          # Inter: (opsz, wght)
    except Exception: pass
    cjk=ImageFont.truetype(str(CJK_FILE),size*4)
    try: cjk.set_variation_by_axes([600 if size in (16,18) else 400])   # Noto Sans SC: (wght)
    except Exception: pass
    data=[]; glyphs=[]
    digit_adv=round(max(latin.getlength(c) for c in '0123456789')/4)
    for ch in chars:
        f=latin if ord(ch)<128 or ch in '¥°' else cjk
        # Fixed canvas around the baseline, then crop after supersampling.
        im=Image.new('L',(size*8,size*8)); d=ImageDraw.Draw(im)
        digit = ch.isascii() and ch.isdigit()
        shift = round((digit_adv - f.getlength(ch)/4)*2) if digit else 0
        d.text((size*2+shift,size*6),ch,font=f,fill=255,anchor='ls')
        im=im.resize((size*2,size*2),Image.Resampling.LANCZOS)
        # Quantize before finding bounds so invisible fringe does not grow boxes.
        im=im.point(lambda a: min(15,(a+8)//17))
        box=im.getbbox()
        adv=digit_adv if ch.isascii() and ch.isdigit() else max(1,round(f.getlength(ch)/4))
        if not box:
            glyphs.append((ord(ch),len(data),0,0,adv,0,0)); continue
        x0,y0,x1,y1=box; w=x1-x0; h=y1-y0
        px=im.load(); start=len(data)
        for y in range(y0,y1):
            for x in range(x0,x1,2):
                data.append((px[x,y]<<4) | (px[x+1,y] if x+1<x1 else 0))
        glyphs.append((ord(ch),start,w,h,adv,x0-size//2,y0-size*3//2))
    lines.append(f'static const uint8_t {name}_DATA[] = {{')
    lines.extend(','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32))
    lines.append('};')
    lines.append(f'static const UiGlyph {name}_GLYPHS[] = {{')
    lines.extend('{'+','.join(map(str,g))+'},' for g in glyphs)
    lines.append('};')
    lines.append(f'static const UiFont {name} = {{{name}_GLYPHS,{name}_DATA,{len(glyphs)}}};')
    print(name,len(glyphs),len(data),'bytes')
(ROOT/'dsh_badge/ui_fonts.h').write_text('\n'.join(lines)+'\n')
