"""Vector star field for RGB565: arcs, constellations, clustered points, no gradient."""
from pathlib import Path
from PIL import Image,ImageDraw
import random,math
ROOT=Path(__file__).resolve().parents[1]
W,H,S=284,240,4
im=Image.new('RGB',(W*S,H*S),(0,0,0));d=ImageDraw.Draw(im)
def line(points,color,width=0.65):d.line([(round(x*S),round(y*S)) for x,y in points],fill=color,width=max(1,round(width*S)))
def ellipse_arc(cx,cy,rx,ry,angle0,angle1,color,rotation=0):
 pts=[]
 for i in range(260):
  a=math.radians(angle0+(angle1-angle0)*i/259);r=math.radians(rotation)
  x,y=rx*math.cos(a),ry*math.sin(a)
  pts.append((cx+x*math.cos(r)-y*math.sin(r),cy+x*math.sin(r)+y*math.cos(r)))
 line(pts,color)
# Partial orbital lines form a scene, without filling the screen with gradients.
ellipse_arc(241,53,91,66,170,360,(22,43,65),-12)
ellipse_arc(241,53,99,71,205,335,(12,26,43),-12)
ellipse_arc(200,286,216,123,193,326,(25,45,67),-8)
ellipse_arc(200,286,220,130,205,275,(11,26,39),-8)
# Constellations occupy the open header and the space between disk label/value.
constellations=[[(104,18),(122,9),(143,19),(164,13)],[(95,154),(114,141),(137,149),(153,139)]]
for pts in constellations:line(pts,(31,56,81),0.6)
im=im.resize((W,H),Image.Resampling.LANCZOS)
p=im.load();rng=random.Random(1028)
# Keep stars outside text and icon footprints, including worst-case values.
protected=[(10,11,86,32),(173,12,274,31),(8,49,157,94),(167,40,274,96),
 (10,114,135,135),(149,114,274,135),(10,141,79,163),(171,140,274,164),
 (10,171,136,191),(149,171,274,191),(10,208,274,232)]
def safe(x,y):return 2<=x<W-2 and 2<=y<H-2 and not any(a<=x<=c and b<=y<=dd for a,b,c,dd in protected)
def point(x,y,col):
 if safe(x,y):p[x,y]=tuple(max(p[x,y][i],col[i]) for i in range(3))
# Distant stars, then a denser curved band through whitespace.
for _ in range(165):
 x,y=rng.randrange(W),rng.randrange(H)
 shade=rng.choice([(20,34,52),(31,47,68),(48,68,88),(74,93,111)])
 point(x,y,shade)
for _ in range(260):
 x=rng.uniform(5,278); y=38+0.18*x+7*math.sin(x/42)+rng.gauss(0,6)
 point(round(x),round(y),rng.choice([(15,27,45),(23,39,60),(34,53,76)]))
# A handful of stronger stars: a bright core and restrained cross-shaped glow.
for x,y in [(122,9),(143,19),(23,40),(159,99),(114,141),(153,139),(110,195),(254,236)]:
 point(x,y,(155,187,216))
 for dx,dy in [(1,0),(-1,0),(0,1),(0,-1)]:point(x+dx,y+dy,(45,74,101))
for pts in constellations:
 for x,y in pts:point(x,y,(108,148,181))
# Sparse row runs; drawFastHLine is reliable on the PSRAM canvas.
runs=[]
for y in range(H):
 row=[]
 for x in range(W):
  r,g,b=p[x,y];row.append(((r>>3)<<11)|((g>>2)<<5)|(b>>3))
 x=0
 while x<W:
  c=row[x];end=x+1
  while end<W and row[end]==c:end+=1
  if c:runs.append((x,y,end-x,c))
  x=end
(ROOT/'dsh_badge/star_background.h').write_text('// Generated by tools/build_star_background.py; no gradients or random runtime flicker.\n#pragma once\n#include <stdint.h>\nstruct StarRun { uint16_t x,y,n,color; };\nstatic const StarRun STAR_RUNS[] = {\n'+'\n'.join('{'+','.join(map(str,r))+'},' for r in runs)+'\n};\n')
im.resize((852,720),Image.Resampling.NEAREST).save(ROOT/'docs/star-depth/background.png')
print(len(runs),'runs;',len(runs)*8,'bytes')
